"""Промпты LLM для Hunter."""


def build_response_draft_prompt(
    *,
    vacancy_text: str,
    category_name: str,
    profile_summary: str,
) -> str:
    vac = (vacancy_text or "")[:2000]
    return (
        "Ты помощник кандидата на подработку в сфере мероприятий и промо (Москва).\n"
        "Составь короткий вежливый текст отклика на вакансию на русском (до 900 символов).\n"
        "Используй ТОЛЬКО факты из анкеты кандидата — ничего не выдумывай.\n"
        "Структура: приветствие → кратко опыт/готовность → контакт из анкеты.\n"
        "Без markdown, без эмодзи в начале каждой строки.\n\n"
        f"Категория: {category_name}\n\n"
        f"Вакансия:\n{vac}\n\n"
        f"Анкета кандидата:\n{profile_summary}\n"
    )
